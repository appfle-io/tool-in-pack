//   권한을 만들어 주고, capabilities/default.json 이 허용한 창(main·tool·notch·search·
//   sticky-*)에서만 호출이 통과한다. postcode·parcel 창은 어떤 capability 에도 없으므로 0개다.
//
//   · 목록은 lib.rs 의 invoke_handler 와 **정확히 같아야** 한다(빠지면 그 커맨드는 다시 열린다).
