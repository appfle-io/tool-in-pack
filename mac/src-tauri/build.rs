//   Tauri 2 의 capabilities 는 core·플러그인 권한은 막지만, invoke_handler 에 등록한 앱 커맨드는
//   app manifest 가 없으면 ACL 검사 대상이 아니라 **어느 창에서든** 부를 수 있었다. 그래서
